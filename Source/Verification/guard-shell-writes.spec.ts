test('the batch classifier is the policy source for names, patterns, generated files and installed trees', () => {
    const repo = scratchRepository();
    try {
        mkdirSync(join(repo.root, '.cratis'));
        writeFileSync(join(repo.root, '.cratis/ai.manifest.json'), '{}');
        const paths = ['.ENV', './missing/../Package.JSON', '.e*', '*crets.env', '.{env,ENV}', '.cl*/settings.json', '.Cratis/AI/rules/x.md', 'Source/Accounts/Registration.ts', 'linked-control', '*.txt', 'notes.md', 'ordinary*.txt'];
        const result = spawnSync('bash', [join(guard, '../cratis-guard-writes.sh'), '--references'], { cwd: repo.root, input: JSON.stringify({ cwd: repo.root, tool_input: { file_paths: paths } }), encoding: 'utf8', env: environment() });
        assert.equal(result.status, 0, result.stderr);
        assert.deepEqual(result.stdout.trim().split('\n'), paths.slice(0, -2));
        assert.equal(result.stderr, '');
        assert.equal(runGuard(payload('touch .Cratis/AI/rules/x.md', repo.root), repo.root).verdict, BLOCK);
    } finally { repo.dispose(); }
});

test('directory references use owned-tree policy without tracking directory changes', async () => {
    const repo = scratchRepository();
    try {
        mkdirSync(join(repo.root, '.cratis'));
        writeFileSync(join(repo.root, '.cratis/ai.manifest.json'), JSON.stringify({ Integrations: [{ Path: '.claude/managed-custom', IsDirectory: true }] }));
        await checkCases([
            [BLOCK, 'cd .claude && echo x > settings.json'],
            [BLOCK, 'pushd .cratis/ai; echo x > ai.manifest.json'],
            [BLOCK, 'cd .pi/extensions && echo x > new.ts'],
            [BLOCK, 'cd .claude/managed-custom && echo x > other.txt'],
            [BLOCK, 'popd; cat .env'], [BLOCK, 'cd sub; cat .env'],
            [ALLOW, 'cd src && echo ok > out.txt'], [ALLOW, 'pushd src; echo ok > out.txt'],
            [ALLOW, 'ls .claude'], [ALLOW, 'ls .cratis/ai'],
        ], repo.root);
        const paths = ['.claude', '.cratis/ai', '.pi/extensions', '.claude/managed-custom', 'src', '.github/workflows'];
        const result = spawnSync('bash', [join(guard, '../cratis-guard-writes.sh'), '--references'], { cwd: repo.root, input: JSON.stringify({ cwd: repo.root, tool_input: { file_paths: paths } }), encoding: 'utf8', env: environment() });
        assert.equal(result.status, 0, result.stderr);
        assert.deepEqual(result.stdout.trim().split('\n'), paths.slice(0, 4), 'only trees owned by the write policy are references');
    } finally { repo.dispose(); }
});

test('Cratis-origin and explicit opt-in policies and the harness escape hatch are preserved', () => {
    const repo = scratchRepository('https://github.com/Cratis/Example.git');
    try {
        assert.equal(runGuard(payload('echo x > Package.json', repo.root), repo.root).verdict, ALLOW);
        mkdirSync(join(repo.root, '.cratis'));
        writeFileSync(join(repo.root, '.cratis/ai.json'), '{"allowDependencyManifestWrites":false}');
        assert.equal(runGuard(payload('echo x > Package.json', repo.root), repo.root).verdict, BLOCK);
        writeFileSync(join(repo.root, '.cratis/ai.json'), '{"allowDependencyManifestWrites":true}');
        assert.equal(runGuard(payload('cp x Package.json', repo.root), repo.root).verdict, ALLOW);
        assert.equal(runGuard(payload('echo x > .env', repo.root), repo.root, { CRATIS_HOOKS_ALLOW_PROTECTED_WRITES: '1' }).verdict, ALLOW);
        assert.equal(runGuard({ tool_input: { file_path: '.env' } }, repo.root).verdict, ALLOW);
    } finally { repo.dispose(); }
});

test('parse, size and classifier failures refuse instead of silently allowing a reference', () => {
    const repo = scratchRepository();
    try {
        for (const command of ["cat '.env", 'cat .env $(echo x)', `cat .env ${'word '.repeat(300)}`]) {
            assert.equal(runGuard(payload(command, repo.root), repo.root).verdict, BLOCK, command);
        }
        const scripts = join(repo.root, 'scripts');
        mkdirSync(scripts);
        const localGuard = join(scripts, 'cratis-guard-shell-writes.sh');
        copyFileSync(guard, localGuard);
        copyFileSync(join(guard, '../hook-lib.sh'), join(scripts, 'hook-lib.sh'));
        for (const classifier of [undefined, 'exit 7\n']) {
            if (classifier) writeFileSync(join(scripts, 'cratis-guard-writes.sh'), classifier);
            const result = spawnSync('bash', [localGuard], { cwd: repo.root, input: JSON.stringify(payload('echo x > .env', repo.root)), encoding: 'utf8', env: environment() });
            assert.equal(result.status, 2, result.stderr);
            assert.match(result.stderr, /could not check/);
        }
    } finally { repo.dispose(); }
});

test('the Pi bridge blocks protected writes but permits a protected read', async () => {
    const saved = process.env.CRATIS_HOOKS_ALLOW_PROTECTED_WRITES;
    process.env.CRATIS_HOOKS_ALLOW_PROTECTED_WRITES = '0';
    const repo = scratchRepository();
    const handlers = new Map<string, (event: unknown, ctx: unknown) => Promise<unknown> | unknown>();
    registerCratisHooks({ on: (event: string, handler: (event: unknown, ctx: unknown) => unknown) => handlers.set(event, handler), registerTool: () => { /* No tools are needed by this fixture. */ } } as unknown as ExtensionAPI);
    try {
        const call = handlers.get('tool_call');
        assert.ok(call);
        const result = await call({ toolName: 'bash', input: { command: 'echo x > .mcp.json' } }, { cwd: repo.root }) as { block?: boolean; reason?: string };
        assert.equal(result?.block, true);
        assert.match(result?.reason ?? '', /BLOCKED by cratis-guard-shell-writes/);
        assert.equal(await call({ toolName: 'bash', input: { command: 'cat .mcp.json' } }, { cwd: repo.root }), undefined);
    } finally {
        if (saved === undefined) delete process.env.CRATIS_HOOKS_ALLOW_PROTECTED_WRITES;
        else process.env.CRATIS_HOOKS_ALLOW_PROTECTED_WRITES = saved;
        repo.dispose();
    }
});
