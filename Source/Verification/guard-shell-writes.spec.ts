import registerCratisHooks from '../../.cratis/ai/harnesses/pi/extensions/cratis-hooks/index.ts';

const guard = resolve(import.meta.dirname, '../../.cratis/ai/hooks/scripts/cratis-guard-shell-writes.sh');
const BLOCK = 'block';
const ALLOW = 'allow';
const payload = (command: string, cwd: string) => ({ cwd, tool_name: 'Bash', tool_input: { command } });
const environment = () => ({ ...process.env, CRATIS_HOOKS_ALLOW_PROTECTED_WRITES: '0' });

function runGuard(input: object, cwd: string, env: NodeJS.ProcessEnv = {}) {
    const result = spawnSync('bash', [guard], { cwd, input: JSON.stringify(input), encoding: 'utf8', env: { ...environment(), ...env } });
    assert.ok(result.status === 0 || result.status === 2, `unexpected guard exit ${result.status}: ${result.stderr}`);
    return { verdict: result.status === 2 ? BLOCK : ALLOW, stdout: result.stdout, stderr: result.stderr };
}

function runGuardAsync(command: string, cwd: string): Promise<ReturnType<typeof runGuard>> {
    return new Promise((resolveRun, reject) => {
        const child = spawn('bash', [guard], { cwd, env: environment() });
        let stdout = '';
        let stderr = '';
        child.stdout.setEncoding('utf8').on('data', chunk => { stdout += chunk; });
        child.stderr.setEncoding('utf8').on('data', chunk => { stderr += chunk; });
        child.on('error', reject);
        child.on('close', status => {
            if (status !== 0 && status !== 2) return reject(new Error(`unexpected guard exit ${status}: ${stderr}`));
            resolveRun({ verdict: status === 2 ? BLOCK : ALLOW, stdout, stderr });
        });
        child.stdin.on('error', () => { /* The refusal can close stdin before its writer. */ });
        child.stdin.end(JSON.stringify(payload(command, cwd)));
    });
}

async function checkCases(cases: Array<[string, string]>, cwd: string) {
    let next = 0;
    const failures: string[] = [];
    const worker = async () => {
        while (next < cases.length) {
            const [expected, command] = cases[next++];
            try {
                const result = await runGuardAsync(command, cwd);
                assert.equal(result.verdict, expected, `${command}\n${result.stderr}`);
                assert.equal(result.stdout, '', command);
                if (expected === BLOCK) assert.match(result.stderr, /BLOCKED by cratis-guard-shell-writes/, command);
                else assert.equal(result.stderr, '', command);
            } catch (error) { failures.push((error as Error).message); }
        }
    };
    await Promise.all(Array.from({ length: Math.min(16, cases.length) }, worker));
    assert.equal(failures.join('\n'), '');
}

function scratchRepository(origin = 'https://github.com/example/app.git') {
    const root = mkdtempSync(join(tmpdir(), 'cratis-shell-writes-'));
    assert.equal(spawnSync('git', ['init', '-q', root]).status, 0);
    assert.equal(spawnSync('git', ['-C', root, 'remote', 'add', 'origin', origin]).status, 0);
    mkdirSync(join(root, 'Source/Accounts'), { recursive: true });
    writeFileSync(join(root, 'Source/Accounts/Registration.ts'), '// @generated by Cratis. DO NOT EDIT.\nexport {};\n');
    writeFileSync(join(root, 'notes.md'), '# Notes\n\nThe marker is `// @generated by Cratis`.\n');
    symlinkSync(join(root, '.mcp.json'), join(root, 'linked-control'));
    return { root, dispose: () => rmSync(root, { recursive: true, force: true }) };
}

