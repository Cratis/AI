import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { chmodSync, existsSync, mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import test from 'node:test';

const runner = resolve(import.meta.dirname, '../../.cratis/ai/hooks/scripts/cratis-run-specs.sh');

type Project = { properties?: Record<string, string>; packages?: string[]; apphost?: boolean; dll?: boolean; output?: string; exit?: number; evaluationExit?: number; report?: number | { total: number; passed: number; failed: number; skipped: number } };

function fixture(projects: Record<string, Project>, arguments_: string[] = [], configuration = 'Debug') {
    const root = realpathSync(mkdtempSync(join(tmpdir(), 'spec-runner-')));
    const log = join(root, 'calls.jsonl');
    const metadata: Record<string, unknown> = {};
    for (const [name, project] of Object.entries(projects)) {
        const path = join(root, name);
        mkdirSync(dirname(path), { recursive: true });
        writeFileSync(path, '<Project />');
        const target = join(root, 'custom output', name.replace(/\.csproj$/, ''), 'renamed.dll');
        mkdirSync(dirname(target), { recursive: true });
        const properties = { IsTestProject: 'true', OutputType: 'Exe', TargetFramework: 'net10.0', TargetFrameworks: '', TargetPath: target, AssemblyName: 'renamed', XunitAutoGeneratedEntryPoint: 'true', ...project.properties };
        metadata[path] = { Properties: properties, Items: { PackageReference: (project.packages ?? ['xunit.v3.mtp-off', 'Microsoft.NET.Test.Sdk']).map(Identity => ({ Identity })) }, evaluationExit: project.evaluationExit };
        const counters = typeof project.report === 'object' ? project.report : { total: project.report ?? 2, passed: project.report ?? 2, failed: 0, skipped: 0 };
        const executable = `#!${process.execPath}\nconst fs = require('node:fs'); const args = process.argv.slice(2); fs.appendFileSync(${JSON.stringify(log)}, JSON.stringify(['suite', ${JSON.stringify(name)}, ...args]) + '\\n'); const trx = args.indexOf('-trx'); if (trx >= 0) fs.writeFileSync(args[trx + 1], '<TestRun><ResultSummary><Counters total="${counters.total}" executed="${counters.passed + counters.failed}" passed="${counters.passed}" failed="${counters.failed}" notExecuted="${counters.skipped}" /></ResultSummary></TestRun>'); console.log(${JSON.stringify(project.output ?? 'Test run summary: Passed!\n  total: 2\n  failed: 0\n  succeeded: 2\n  skipped: 0')}); process.exit(${project.exit ?? 0});\n`;
        if (project.dll !== false) writeFileSync(target, executable);
        if (project.apphost !== false) { writeFileSync(target.slice(0, -4), executable); chmodSync(target.slice(0, -4), 0o755); }
    }
    writeFileSync(join(root, 'Repo.slnx'), '<Solution />');
    const dotnet = join(root, 'dotnet');
    writeFileSync(dotnet, `#!${process.execPath}
const fs = require('node:fs'); const cp = require('node:child_process');
const args = process.argv.slice(2); fs.appendFileSync(${JSON.stringify(log)}, JSON.stringify(args) + '\\n');
const metadata = ${JSON.stringify(metadata)};
if (args[0] === 'sln') { console.log('Project(s)\\n----------\\n' + ${JSON.stringify(Object.keys(projects).join('\n'))}); }
else if (args[0] === 'msbuild') { const value = metadata[args[1]]; if (value.evaluationExit) process.exit(value.evaluationExit); console.log(JSON.stringify(value)); }
else if (args[0] === 'test') { console.log('Passed! - Failed: 0, Passed: 2, Skipped: 0, Total: 2'); }
else if (args[0]?.endsWith('.dll')) { const result = cp.spawnSync(process.execPath, args, { stdio: 'inherit' }); process.exit(result.status ?? 1); }
else { console.error('Unexpected dotnet invocation', args); process.exit(99); }
`);
    chmodSync(dotnet, 0o755);
    const result = spawnSync('bash', [runner, '--configuration', configuration, '--no-build', ...arguments_], { cwd: root, encoding: 'utf8', env: { ...process.env, PATH: `${root}:${process.env.PATH}` } });
    const calls = existsSync(log) ? readFileSync(log, 'utf8').trim().split('\n').map(line => JSON.parse(line) as string[]) : [];
    rmSync(root, { recursive: true, force: true });
    return { ...result, calls, text: result.stdout + result.stderr };
}

function passed(result: ReturnType<typeof fixture>) {
    assert.equal(result.status, 0, result.text);
    assert.equal(result.calls.some(call => ['restore', 'build', 'run'].includes(call[0])), false);
    assert.equal(result.calls.filter(call => call[0] === 'msbuild').every(call => call.includes('-p:Configuration=Debug') || call.includes('-p:Configuration=Release')), true);
}

test('xUnit v3 mtp-off takes precedence over Test.Sdk and uses the evaluated custom output', () => {
    const result = fixture({ 'Source/My specs.csproj': {} });
    passed(result);
    assert.equal(result.calls.some(call => call[0] === 'test'), false);
    assert.match(result.text, /xunit.*net10\.0/);
    assert.equal(result.calls.find(call => call[0] === 'suite')?.[2], '-trx');
});

test('a mixed solution executes supported projects independently in solution order', () => {
    const result = fixture({
        'Xunit.csproj': {},
        'TUnit.csproj': { packages: ['TUnit'], properties: { IsTestingPlatformApplication: 'true' } },
        'Native.csproj': { packages: ['Cratis.Specifications.Runner'], properties: { IsTestingPlatformApplication: 'true' } },
        'Legacy.csproj': { packages: ['xunit', 'Microsoft.NET.Test.Sdk'], properties: { OutputType: 'Library' } },
        'Product.csproj': { packages: [], properties: { IsTestProject: 'false', OutputType: 'Library' } },
    });
    passed(result);
    assert.deepEqual(result.calls.filter(call => call[0] === 'suite').map(call => call[1]), ['Xunit.csproj', 'TUnit.csproj', 'Native.csproj']);
    const legacy = result.calls.find(call => call[0] === 'test');
    assert.deepEqual(legacy?.slice(2), ['--configuration', 'Debug', '--no-build', '--framework', 'net10.0']);
    assert.match(result.text, /SKIP.*Product/);
});

test('legacy VSTest projects can have an SDK-generated executable entrypoint', () => {
    const result = fixture({ 'Legacy.csproj': { packages: ['xunit', 'Microsoft.NET.Test.Sdk'] } });
    passed(result);
    assert.equal(result.calls.filter(call => call[0] === 'test').length, 1);
    assert.equal(result.calls.some(call => call[0] === 'suite'), false);
});

test('evaluated MTP applications work without direct package references', () => {
    passed(fixture({ 'Platform.csproj': { packages: [], properties: { IsTestingPlatformApplication: 'true' } } }));
});

for (const [format, packages] of [
    ['MTP', ['TUnit']],
    ['TRX', ['xunit.v3.mtp-off', 'Microsoft.NET.Test.Sdk']],
    ['native', ['Cratis.Specifications.Runner']],
] as [string, string[]][]) {
    for (const passedCount of [2, 0]) {
        test(`${format} ${passedCount ? 'accepts mixed passed and skipped tests' : 'refuses all-skipped tests'}`, () => {
            const skipped = 3 - passedCount;
            const result = fixture({ 'Specs.csproj': {
                packages,
                report: { total: 3, passed: passedCount, failed: 0, skipped },
                output: `total: 3\nfailed: 0\nsucceeded: ${passedCount}\nskipped: ${skipped}`,
            } });
            if (passedCount) passed(result);
            else {
                assert.notEqual(result.status, 0, result.text);
                assert.match(result.text, /not all specifications passed/);
            }
        });
    }
}

test('a missing apphost runs the evaluated dll without MSBuild', () => {
    const result = fixture({ 'Specs.csproj': { apphost: false } });
    passed(result);
    assert.equal(result.calls.some(call => call[0].endsWith('renamed.dll')), true);
});

test('all target frameworks are evaluated with the requested configuration', () => {
    const result = fixture({ 'Specs.csproj': { properties: { TargetFramework: '', TargetFrameworks: 'net9.0;net10.0' } } }, [], 'Release');
    passed(result);
    assert.deepEqual(result.calls.filter(call => call[0] === 'msbuild').slice(1).map(call => call.find(value => value.startsWith('-p:TargetFramework='))), ['-p:TargetFramework=net9.0', '-p:TargetFramework=net10.0']);
    assert.equal(result.calls.filter(call => call[0] === 'suite').length, 2);
});

test('explicit project and framework selection does not expand scope', () => {
    const result = fixture({ 'One.csproj': { properties: { TargetFramework: '', TargetFrameworks: 'net9.0;net10.0' } }, 'Two.csproj': {} }, ['--project', 'One.csproj', '--framework', 'net9.0']);
    passed(result);
    assert.equal(result.calls.some(call => call[0] === 'sln'), false);
    assert.equal(result.calls.filter(call => call[0] === 'suite').length, 1);
});

for (const [name, project, message] of [
    ['missing output', { apphost: false, dll: false }, /matching.*build/i],
    ['metadata failure', { evaluationExit: 7 }, /evaluat/i],
    ['unknown test runner', { packages: ['Unknown.Test.Framework'] }, /unsupported|unknown/i],
    ['custom application entrypoint', { properties: { XunitAutoGeneratedEntryPoint: 'false' } }, /override|entrypoint/i],
    ['zero-selected suite', { report: 0 }, /zero|no tests/i],
    ['MTP zero-selected suite', { packages: ['TUnit'], output: 'total: 0\nfailed: 0\nsucceeded: 0' }, /zero|no tests/i],
    ['unverified native counts', { packages: ['TUnit'], output: 'Finished successfully' }, /unverified|count/i],
] as [string, Project, RegExp][]) {
    test(`refuses ${name}`, () => {
        const result = fixture({ 'Specs.csproj': project });
        assert.notEqual(result.status, 0, result.text);
        assert.match(result.text, message);
    });
}

test('suite failure preserves the child exit and stops dependent execution', () => {
    const result = fixture({ 'Fail.csproj': { exit: 17 }, 'Later.csproj': {} });
    assert.equal(result.status, 17, result.text);
    assert.equal(result.calls.filter(call => call[0] === 'suite').length, 1);
});

test('non-test-only solutions explicitly report no verified specifications', () => {
    const result = fixture({ 'Product.csproj': { packages: [], properties: { IsTestProject: 'false', OutputType: 'Library' } } });
    passed(result);
    assert.match(result.text, /NO-OP.*no test projects/i);
});
