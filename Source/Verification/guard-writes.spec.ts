const BLOCK = 'block';
const ALLOW = 'allow';

function runGuard(payload: object, cwd: string, env: NodeJS.ProcessEnv = {}): { verdict: string; stdout: string; stderr: string } {
    const result = spawnSync('bash', [guard], {
        cwd,
        input: JSON.stringify(payload),
        encoding: 'utf8',
        env: { ...process.env, CRATIS_HOOKS_ALLOW_PROTECTED_WRITES: '0', ...env },
    });
    assert.ok(result.status === 0 || result.status === 2, `unexpected guard exit ${result.status}: ${result.stderr}`);
    return { verdict: result.status === 2 ? BLOCK : ALLOW, stdout: result.stdout, stderr: result.stderr };
}

/** Same contract as runGuard without blocking the event loop, so independent cases can overlap their process spawns. */
function runGuardAsync(payload: object, cwd: string, env: NodeJS.ProcessEnv = {}): Promise<{ verdict: string; stdout: string; stderr: string }> {
    return new Promise((resolveRun, reject) => {
        const child = spawn('bash', [guard], { cwd, env: { ...process.env, CRATIS_HOOKS_ALLOW_PROTECTED_WRITES: '0', ...env } });
        let stdout = '';
        let stderr = '';
        child.stdout.setEncoding('utf8').on('data', chunk => { stdout += chunk; });
        child.stderr.setEncoding('utf8').on('data', chunk => { stderr += chunk; });
        child.on('error', reject);
        child.on('close', status => {
            if (status !== 0 && status !== 2) return reject(new Error(`unexpected guard exit ${status}: ${stderr}`));
            resolveRun({ verdict: status === 2 ? BLOCK : ALLOW, stdout, stderr });
        });
        child.stdin.on('error', () => {});
        child.stdin.end(JSON.stringify(payload));
    });
}

/** Runs independent cases with bounded concurrency; the first failed assertion rejects the whole run. */
async function forEachConcurrently<T>(items: T[], action: (item: T) => Promise<void>, limit = 16): Promise<void> {
    let next = 0;
    const worker = async () => { while (next < items.length) await action(items[next++]); };
    await Promise.all(Array.from({ length: Math.min(limit, items.length) }, worker));
}

/** A throwaway repository holding one real generated proxy, one file that merely mentions the marker, and a manifest. */
function scratchRepository(origin?: string): { root: string; generated: string; mention: string; manifest: string; dispose: () => void } {
    const root = mkdtempSync(join(tmpdir(), 'cratis-guard-'));
    assert.equal(spawnSync('git', ['init', '-q', root]).status, 0);
    if (origin) assert.equal(spawnSync('git', ['-C', root, 'remote', 'add', 'origin', origin]).status, 0);
    mkdirSync(join(root, 'Source', 'Accounts', 'Registration'), { recursive: true });
    const generated = join(root, 'Source', 'Accounts', 'Registration', 'Registration.ts');
    writeFileSync(generated, '// @generated by Cratis. DO NOT EDIT.\nexport class Register {}\n');
    const mention = join(root, 'Source', 'Accounts', 'Registration', 'notes.md');
    writeFileSync(mention, '# Notes\n\nProxies carry a `// @generated by Cratis` header; never edit them.\n');
    const manifest = join(root, 'Directory.Packages.props');
    writeFileSync(manifest, '<Project />\n');
    return { root, generated, mention, manifest, dispose: () => rmSync(root, { recursive: true, force: true }) };
}

test('the write guard refuses generated output and allows a file that merely mentions the marker', () => {
    const repo = scratchRepository();
    try {
        const cases: Array<[expected: string, name: string, payload: object]> = [
            [BLOCK, 'edit a generated proxy', { cwd: repo.root, tool_name: 'Edit', tool_input: { file_path: repo.generated, new_string: 'x' } }],
            [BLOCK, 'overwrite a generated proxy', { cwd: repo.root, tool_name: 'Write', tool_input: { file_path: repo.generated, content: 'x' } }],
            [ALLOW, 'edit a file that only mentions the marker in prose', { cwd: repo.root, tool_name: 'Edit', tool_input: { file_path: repo.mention, new_string: 'more prose' } }],
            [BLOCK, 'author a new file whose content opens with the generated header', { cwd: repo.root, tool_name: 'Write', tool_input: { file_path: join(repo.root, 'Source', 'New.ts'), content: '// @generated by Cratis\nexport {};\n' } }],
            [ALLOW, 'author a new file that quotes the header below its first lines', { cwd: repo.root, tool_name: 'Write', tool_input: { file_path: join(repo.root, 'Source', 'New.md'), content: '# Title\n\n\n\n\n\nThe header reads `// @generated by Cratis`.\n' } }],
            [BLOCK, 'edit a dependency manifest', { cwd: repo.root, tool_name: 'Edit', tool_input: { file_path: repo.manifest, new_string: 'x' } }],
            [ALLOW, 'edit an ordinary source file', { cwd: repo.root, tool_name: 'Edit', tool_input: { file_path: join(repo.root, 'Source', 'Accounts', 'Registration', 'Registration.cs'), new_string: 'x' } }],
            [ALLOW, 'a call with no file path is not the guard\u2019s business', { cwd: repo.root, tool_name: 'Bash', tool_input: { command: `cat ${repo.generated}` } }],
        ];
        for (const [expected, name, payload] of cases) {
            const { verdict, stderr } = runGuard(payload, repo.root);
            assert.equal(verdict, expected, `${name}\n${stderr}`);
            if (expected === BLOCK) assert.match(stderr, /BLOCKED by cratis-guard-writes/);
        }
    } finally {
        repo.dispose();
    }
});

