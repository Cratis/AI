import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const fixture = name => new URL(`./fixtures/solocrm-drift/${name}`, import.meta.url);
const readJson = name => JSON.parse(readFileSync(fixture(name), 'utf8'));

function change(path, body, before = path) {
    return `diff --git a/${before} b/${path}\n--- a/${before}\n+++ b/${path}\n${body}\n`;
}

function miniatureMap(paths = ['Source/Crm/Tags/**']) {
    return {
        watermarks: { from: { revision: 'before', inputDigest: 'fixture-before' }, to: { revision: 'after', inputDigest: 'fixture-after' } },
        flows: [{ id: 'Tags', evidenceIds: ['RE-E1'], paths }],
    };
}

function fixtureChecks(scopeDrift) {
    const map = readJson('evidence-map.json');
    const diff = readFileSync(fixture('change.diff'), 'utf8');
    const expected = readJson('expected.json');
    const actual = scopeDrift(diff, map);
    assert.deepEqual(actual, expected);
    assert.deepEqual(scopeDrift(diff, map), actual, 'deterministic output');
    assert.equal(map.flows.length, 31);
    assert.deepEqual(actual.newFlowCandidates[0].symbols, ['IsDormant', 'IsDueToday', 'IsOverdue']);
    assert.ok(actual.untouchedFlows.includes('Crm/Tags/Tags'));
    const cli = spawnSync(process.execPath, [fileURLToPath(new URL('./drift-scope.mjs', import.meta.url)),
        fileURLToPath(fixture('change.diff')), fileURLToPath(fixture('evidence-map.json'))], { encoding: 'utf8', timeout: 10000 });
    assert.equal(cli.error, undefined);
    assert.equal(cli.status, 0, cli.stderr);
    assert.deepEqual(JSON.parse(cli.stdout), expected);
    return 8;
}

function classificationChecks(scopeDrift) {
    const map = miniatureMap();
    const run = (path, body, before) => scopeDrift(change(path, body, before), map);
    assert.equal(run('Source/Crm/Tags/Tags.cs', '@@ -1 +1 @@\n-    old();\n+new();').hunks[0].classification, 'process');
    assert.equal(run('Source/Crm/Tags/Tags.cs', '@@ -1 +1 @@\n-    same();\n+same();').hunks[0].classification, 'structure-only');
    assert.equal(run('Source/Crm/Tags/Tags.cs', '@@ -1 +1 @@\n-Print("a b");\n+Print("ab");').hunks[0].classification, 'process');
    assert.equal(run('Source/Crm/Tags/Tags.cs', '@@ -1 +0,0 @@\n-DeleteTag();').touchedFlows[0], 'Tags');
    assert.equal(run('Source/Crm/New/New.cs', '@@ -0,0 +1 @@\n+NewRule();').newFlowCandidates.length, 1);
    assert.equal(run('Source/dist/app.js', '@@ -1 +1 @@').hunks[0].reason, 'build output');
    assert.equal(run('Source/.cratis-render.json', '@@ -1 +1 @@').hunks[0].reason, 'scene/build artifact');
    assert.equal(run('Source/Crm/Tags/Tags.ts', '@@ -0,0 +1 @@\n+export const rule = 1;').hunks[0].classification, 'process');
    assert.equal(run('Source/Crm/Tags/Tags.cs', '@@ -0,0 +2 @@\n+// @generated by Cratis\n+// DO NOT EDIT').hunks[0].classification, 'process');
    return 9;
}

function renameAndMappingChecks(scopeDrift) {
    const map = miniatureMap();
    const renamed = 'diff --git a/Source/Crm/Tags/Tags.cs b/Source/Moved.cs\nsimilarity index 100%\nrename from Source/Crm/Tags/Tags.cs\nrename to Source/Moved.cs\n';
    assert.equal(scopeDrift(renamed, map).hunks[0].classification, 'structure-only');
    const changed = change('Source/Moved.cs', '@@ -1 +1 @@\n-old();\n+changed();', 'Source/Crm/Tags/Tags.cs');
    assert.deepEqual(scopeDrift(changed, map).touchedFlows, ['Tags']);
    const mixed = change('Source/Crm/Tags/Tags.cs', '@@ -1 +1 @@\n- same();\n+same();\n@@ -9 +9 @@\n-old();\n+new();');
    assert.deepEqual(scopeDrift(mixed, map).hunks.map(hunk => hunk.classification), ['structure-only', 'process']);
    const oneSegment = miniatureMap(['Source/*/Tags.cs']);
    assert.equal(scopeDrift(change('Source/Crm/Tags.cs', '@@ -1 +1 @@\n+x'), oneSegment).touchedFlows.length, 1);
    assert.equal(scopeDrift(change('Source/Crm/Other/Tags.cs', '@@ -1 +1 @@\n+x'), oneSegment).touchedFlows.length, 0);
    const literal = miniatureMap(['Source/a.b.cs']);
    assert.equal(scopeDrift(change('Source/axb.cs', '@@ -1 +1 @@\n+x'), literal).touchedFlows.length, 0);
    return 6;
}

function rejectionChecks(scopeDrift) {
    const diff = change('Source/Crm/Tags/Tags.cs', '@@ -1 +1 @@\n+x');
    assert.throws(() => scopeDrift('', miniatureMap()), /unified diff/);
    for (const map of [null, {}, { watermarks: {} }, { watermarks: { from: { revision: 'x' } } }]) {
        assert.throws(() => scopeDrift(diff, map), /revision or inputDigest/);
    }
    for (const flows of [[], null, [{ id: 'Tags', paths: [] }], [miniatureMap().flows[0], miniatureMap().flows[0]]]) {
        assert.throws(() => scopeDrift(diff, { ...miniatureMap(), flows }), /flows|paths|Duplicate flow/);
    }
    return 9;
}

export function selfTest(scopeDrift) {
    const checks = fixtureChecks(scopeDrift) + classificationChecks(scopeDrift) + renameAndMappingChecks(scopeDrift) + rejectionChecks(scopeDrift);
    console.log(`drift-scope self-test: ${checks} checks passed; SoloCrm: 3 process, 4 structure-only, 2 touched, 29 kept, Today candidates IsDormant/IsDueToday/IsOverdue`);
}
