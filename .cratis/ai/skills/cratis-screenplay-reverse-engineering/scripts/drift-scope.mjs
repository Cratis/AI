import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

function nonempty(value) {
    return typeof value === 'string' && value.trim().length > 0;
}

function strings(value) {
    return Array.isArray(value) && value.length > 0 && value.every(nonempty);
}

function validateWatermark(mark, side) {
    const valid = ['revision', 'inputDigest'].every(key => nonempty(mark?.[key]));
    if (!valid) throw new Error(`Missing ${side} revision or inputDigest`);
}

function validateFlow(flow) {
    const valid = [nonempty(flow?.id), strings(flow?.paths), strings(flow?.evidenceIds)].every(Boolean);
    if (!valid) throw new Error('Each flow needs id, paths and evidenceIds');
}

function validateMap(map) {
    for (const side of ['from', 'to']) validateWatermark(map?.watermarks?.[side], side);
    if (!Array.isArray(map.flows)) throw new Error('Evidence map needs nonempty flows');
    if (map.flows.length === 0) throw new Error('Evidence map needs nonempty flows');
    map.flows.forEach(validateFlow);
    const ids = map.flows.map(flow => flow.id);
    if (new Set(ids).size !== ids.length) throw new Error('Duplicate flow ids');
}

/** Deliberately small glob language: * matches one path segment, ** crosses segments. */
function matches(path, glob) {
    const expression = glob.split(/(\*\*|\*)/).map(part => {
        if (part === '**') return '.*';
        if (part === '*') return '[^/]*';
        return part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    }).join('');
    return new RegExp(`^${expression}$`).test(path);
}

function addLine(file, line) {
    if (line.startsWith('@@ ')) file.hunks.push({ header: line, lines: [] });
    else if (file.hunks.length > 0) file.hunks.at(-1).lines.push(line);
    else file.metadata.push(line);
}

function parseDiff(diff) {
    const files = [];
    for (const line of diff.replaceAll('\r\n', '\n').split('\n')) {
        const header = /^diff --git a\/(.+) b\/(.+)$/.exec(line);
        if (header) files.push({ before: header[1], path: header[2], metadata: [], hunks: [] });
        else if (files.length > 0) addLine(files.at(-1), line);
    }
    if (files.length === 0) throw new Error('Expected a Git unified diff with diff --git headers');
    return files;
}

const artifactRules = [
    { pattern: /(^|\/)(yarn\.lock|package-lock\.json|pnpm-lock\.yaml|packages\.lock\.json)$/, reason: 'lockfile' },
    { pattern: /(^|\/)(scene\.json|stage-scene\.json|\.cratis-render\.json)$/, reason: 'scene/build artifact' },
    { pattern: /(^|\/)(obj|bin|dist)\//, reason: 'build output' },
];

function generatedProxy(file) {
    if (!/\.tsx?$/.test(file.path)) return false;
    const text = file.hunks.flatMap(hunk => hunk.lines).join('\n');
    return [/@generated by Cratis/, /DO NOT EDIT/].every(marker => marker.test(text));
}

function artifactReason(file) {
    const rule = artifactRules.find(rule => rule.pattern.test(file.path));
    if (rule) return rule.reason;
    return generatedProxy(file) ? 'generated TypeScript proxy' : null;
}

function indentationOnly(lines) {
    const content = prefix => lines.filter(line => line.startsWith(prefix)).map(line => line.slice(1).trim()).filter(Boolean);
    const removed = content('-');
    const added = content('+');
    return removed.length + added.length > 0 && JSON.stringify(removed) === JSON.stringify(added);
}

function unchangedRename(file, hunk) {
    if (hunk) return false;
    if (file.before === file.path) return false;
    return file.metadata.includes('similarity index 100%');
}

function classify(file, hunk, artifact) {
    if (artifact) return { classification: 'structure-only', reason: artifact };
    if (hunk && indentationOnly(hunk.lines)) return { classification: 'structure-only', reason: 'indentation/blank-line change only' };
    if (unchangedRename(file, hunk)) return { classification: 'structure-only', reason: 'unchanged-content rename' };
    return { classification: 'process', reason: 'behavior source or unrecognized change; re-derive before deciding drift' };
}

function symbols(lines) {
    const names = lines.filter(line => line.startsWith('+')).flatMap(line => {
        const match = /public static \S+ (\w+)\(/.exec(line);
        return match ? [match[1]] : [];
    });
    return [...new Set(names)].sort();
}

function fileScope(file, flows) {
    const artifact = artifactReason(file);
    const mapped = flows.filter(flow => flow.paths.some(glob => matches(file.path, glob) || matches(file.before, glob)));
    return (file.hunks.length ? file.hunks : [null]).map(hunk => {
        const verdict = classify(file, hunk, artifact);
        return {
            path: file.path, before: file.before, hunk: hunk?.header ?? null, ...verdict,
            flows: verdict.classification === 'process' ? mapped.map(flow => flow.id).sort() : [],
        };
    });
}

/** Work-list hints, not semantic proof of drift or permission to advance a watermark. */
export function scopeDrift(diff, map) {
    validateMap(map);
    const files = parseDiff(diff);
    const hunks = files.flatMap(file => fileScope(file, map.flows));
    const touchedFlows = [...new Set(hunks.flatMap(hunk => hunk.flows))].sort();
    const candidates = new Set(hunks.filter(hunk => hunk.classification === 'process' && hunk.flows.length === 0).map(hunk => hunk.path));
    const newFlowCandidates = [...candidates].sort().map(path => ({
        path, symbols: symbols(files.filter(file => file.path === path).flatMap(file => file.hunks.flatMap(hunk => hunk.lines))),
        reason: 'unmapped source; intake a candidate flow (including deletions or unsupported changes)',
    }));
    return {
        watermarks: map.watermarks, hunks, touchedFlows,
        untouchedFlows: map.flows.map(flow => flow.id).filter(id => !touchedFlows.includes(id)).sort(),
        newFlowCandidates,
        structureOnlyCount: hunks.filter(hunk => hunk.classification === 'structure-only').length,
    };
}

export async function main(args = process.argv.slice(2)) {
    try {
        if (args.length === 1 && args[0] === '--self-test') {
            const { selfTest } = await import('./drift-scope-self-test.mjs');
            selfTest(scopeDrift);
            return 0;
        }
        if (args.length !== 2) throw new Error('Usage: node drift-scope.mjs <diff> <evidence-map.json> | --self-test');
        console.log(JSON.stringify(scopeDrift(readFileSync(args[0], 'utf8'), JSON.parse(readFileSync(args[1], 'utf8'))), null, 2));
        return 0;
    } catch (error) {
        console.error(`drift-scope: ${error.message}`);
        return 1;
    }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) process.exitCode = await main();
